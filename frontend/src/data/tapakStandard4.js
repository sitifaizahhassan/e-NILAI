// Helper: get all sub-aspek flat list
export function getAllSubAspek() {
  return ASPEK_LIST.flatMap((a) => a.subAspek);
}

// Helper: get all items flat list
export function getAllItems() {
  return getAllSubAspek().flatMap((sa) => sa.items);
}

// Helper: build initial scores object (all null)
export function buildInitialScores() {
  const scores = {};
  getAllItems().forEach((item) => {
    scores[item.id] = null;
  });
  return scores;
}

// Taraf PdP based on total score %
export function getTarafPdP(pct) {
  if (pct >= 85) return "CEMERLANG";
  if (pct >= 70) return "BAIK";
  if (pct >= 55) return "SEDERHANA";
  return "PERLU TINDAKAN SEGERA";
}
