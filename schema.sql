ALTER TABLE public.profiles
  ADD COLUMN IF NOT EXISTS no_kp TEXT,
  ADD COLUMN IF NOT EXISTS jawatan TEXT,
  ADD COLUMN IF NOT EXISTS gred TEXT,
  ADD COLUMN IF NOT EXISTS opsyen TEXT;

CREATE TABLE IF NOT EXISTS public.pencerapan_kendiri (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  form_data JSONB NOT NULL DEFAULT '{}'::jsonb,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'submitted', 'reviewed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT pencerapan_kendiri_user_id_key UNIQUE (user_id)
);

CREATE TABLE IF NOT EXISTS public.pencerapan_1 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  form_data JSONB NOT NULL DEFAULT '{}'::jsonb,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'submitted', 'reviewed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT pencerapan_1_user_id_key UNIQUE (user_id)
);

CREATE TABLE IF NOT EXISTS public.pencerapan_2 (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users (id) ON DELETE CASCADE,
  form_data JSONB NOT NULL DEFAULT '{}'::jsonb,
  status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'submitted', 'reviewed')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT pencerapan_2_user_id_key UNIQUE (user_id)
);

CREATE INDEX IF NOT EXISTS idx_pencerapan_kendiri_user_id ON public.pencerapan_kendiri (user_id);
CREATE INDEX IF NOT EXISTS idx_pencerapan_1_user_id ON public.pencerapan_1 (user_id);
CREATE INDEX IF NOT EXISTS idx_pencerapan_2_user_id ON public.pencerapan_2 (user_id);

ALTER TABLE public.pencerapan_kendiri ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pencerapan_1 ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pencerapan_2 ENABLE ROW LEVEL SECURITY;

