BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'pencerapan_kendiri' AND policyname = 'pencerapan_kendiri_owner_select'
  ) THEN
    CREATE POLICY pencerapan_kendiri_owner_select
      ON public.pencerapan_kendiri
      FOR SELECT
      USING (auth.uid() = user_id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'pencerapan_kendiri' AND policyname = 'pencerapan_kendiri_owner_insert'
  ) THEN
    CREATE POLICY pencerapan_kendiri_owner_insert
      ON public.pencerapan_kendiri
      FOR INSERT
      WITH CHECK (auth.uid() = user_id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'pencerapan_kendiri' AND policyname = 'pencerapan_kendiri_owner_update'
  ) THEN
    CREATE POLICY pencerapan_kendiri_owner_update
      ON public.pencerapan_kendiri
      FOR UPDATE
      USING (auth.uid() = user_id)
      WITH CHECK (auth.uid() = user_id);
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_policies
    WHERE schemaname = 'public' AND tablename = 'pencerapan_kendiri' AND policyname = 'pencerapan_kendiri_admin_all'
  ) THEN
    CREATE POLICY pencerapan_kendiri_admin_all
      ON public.pencerapan_kendiri
      FOR ALL
      USING (EXISTS (
        SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin'
      ))
      WITH CHECK (EXISTS (
        SELECT 1 FROM public.profiles p WHERE p.id = auth.uid() AND p.role = 'admin'
      ));
  END IF;
END $$;

